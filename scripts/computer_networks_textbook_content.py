def computer_network_nodes() -> list[dict]:
    nodes = _all_nodes()[0]
    return [
        node for node in nodes
        if node["code"] == "cs408.cn" or node["code"].startswith("cs408.cn.topic.")
    ]


def render_pages() -> dict[str, str]:
    nodes = computer_network_nodes()
    topic_nodes = [node for node in nodes if node["code"] != "cs408.cn"]
    names = {node["name"] for node in topic_nodes}
    if names != set(DETAILS):
        raise ValueError(
            f"topic_content_coverage_mismatch: missing={names - set(DETAILS)}, extra={set(DETAILS) - names}"
        )

    pages: dict[str, str] = {}
    for node in nodes:
        code, name = node["code"], node["name"]
        header = (
            f"<!-- kp:{code} -->\n<!-- knowledge-node-lesson:v3; code={code} -->\n"
            f"{QUALITY_MARKER}\n# {name}\n\n"
        )
        if code == "cs408.cn":
            children = "\n".join(
                f"- [{item['name']}](/knowledge/{item['code']}/lesson)" for item in topic_nodes
            )
            body = (
                f"## 本章导读与学习路径\n\n{GUIDE.strip()}\n\n## 知识节点\n\n{children}\n\n"
                "## 阅读边界\n\n本页是章节导读，不替代下方专题的专门讲解。节点按本项目当前知识树组织，"
                "不表示官方考纲完整性；练习题及来源由关联题库提供。"
            )
        else:
            raw = DETAILS[name].strip()
            if "**例题。**" not in raw or "**分析与逐步解答。**" not in raw:
                raise ValueError(f"missing_topic_specific_worked_example:{code}")
            body = (
                "## 概念、定义与适用条件\n\n" + raw
                + "\n\n## 阅读总结\n\n"
                + "做题时明确协议层、单位和题设约定，逐步保留封装字段/状态或计算过程并检查边界；练习从该节点关联题库获取，本讲解不重复收录练习。"
            )
        pages[f"{code}.md"] = header + body.strip() + "\n"
    return pages


def main() -> None:
    pages = render_pages()
    start = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    count = int(sys.argv[2]) if len(sys.argv) > 2 else len(pages)
    result = []
    for name, new in list(pages.items())[start : start + count]:
        path = PROJECT_ROOT / "seed" / "lessons" / name
        result.append({"name": name, "old": path.read_text(encoding="utf-8"), "new": new})
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
