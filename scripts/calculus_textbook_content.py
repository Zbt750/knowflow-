def calculus_nodes():
    nodes = _all_nodes()[0]
    by_code = {node["code"]: node for node in nodes}
    selected = []
    for node in nodes:
        current = node
        seen = set()
        while current is not None and current["code"] not in seen:
            seen.add(current["code"])
            if current["code"] == "math.calculus":
                if ".family." not in node["code"]:
                    selected.append(node)
                break
            current = by_code.get(current.get("parent_code"))
    return selected


